// Builds src/data/podgo-catalog.gen.ts from fargraph/pod-go-presets (MIT),
// registry/model-catalog/podgo-edit-2.50.json — POD Go Edit 2.50's own model database.
//
//   node scripts/build-podgo-catalog.mjs /path/to/podgo-edit-2.50.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-podgo-catalog.mjs podgo-edit-2.50.json");
  process.exit(2);
}
const catalog = JSON.parse(readFileSync(src, "utf8"));
const TYPE = { 0: "i", 1: "f", 2: "b" };
const models = {};
for (const [id, m] of Object.entries(catalog.models).sort(([a], [b]) => a.localeCompare(b))) {
  if (id.startsWith("@")) continue;
  const params = {};
  for (const p of m.params ?? []) {
    if (!p.symbolicID || p.symbolicID.startsWith("@")) continue;
    const t = TYPE[p.valueType];
    if (!t) continue;
    params[p.symbolicID] = [p.name ?? p.symbolicID, t, p.min === false ? 0 : p.min, p.max === true ? 1 : p.max, p.default, p.displayType ?? ""];
  }
  models[id] = { n: m.name ?? id, c: m.category ?? "", d: m.dsp_load ?? 0, p: params };
}
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "data", "podgo-catalog.gen.ts");
writeFileSync(
  target,
  `// Generated by scripts/build-podgo-catalog.mjs. Do not edit by hand.\n` +
    `// Model data from POD Go Edit ${catalog.provenance?.editor_version ?? ""} via fargraph/pod-go-presets (MIT). See src/data/HX_CATALOG_NOTICE.md.\n` +
    `/* eslint-disable */\n` +
    `export const PODGO_CATALOG_JSON = ${JSON.stringify(JSON.stringify({ models }))};\n`,
);
console.log(`wrote ${Object.keys(models).length} POD Go models to ${target}`);
