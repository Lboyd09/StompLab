/** Whether a recording has two distinct electric guitar parts. Unknown stays hidden. */

export type GuitarArrangement = "single" | "dual" | "unknown";

function norm(s: string): string {
  return s
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

