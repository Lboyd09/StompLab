function hit(hay: string, needles: string[]): boolean {
  if (!hay) return false;
  return needles.some((n) => {
    if (!n.includes(" ")) return hay === n;
    return hay === n || ` ${hay} `.includes(` ${n} `);
  });
}

/** Dual only when we know there are two guitar parts. Otherwise hide the picker. */
export function guitarArrangement(song: string, artist?: string): GuitarArrangement {
  const title = norm(song);
  const who = norm(artist ?? "");
  if (!title && !who) return "unknown";
  if (who && hit(who, DUAL_ARTISTS)) return "dual";
  if (who && hit(who, SINGLE_ARTISTS)) return "single";
  if (hit(title, DUAL_SONGS)) return "dual";
  if (hit(title, SINGLE_SONGS)) return "single";
  return "unknown";
}
